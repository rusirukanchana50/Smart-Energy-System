package lk.ac.ruh.eng.energy;

import lk.ac.ruh.eng.energy.model.Alert;
import lk.ac.ruh.eng.energy.model.Building;
import lk.ac.ruh.eng.energy.model.EnergyReading;
import lk.ac.ruh.eng.energy.repository.AlertRepository;
import lk.ac.ruh.eng.energy.repository.BuildingRepository;
import lk.ac.ruh.eng.energy.repository.EnergyReadingRepository;
import lk.ac.ruh.eng.energy.service.AlertService;
import lk.ac.ruh.eng.energy.service.EnergyService;
import lk.ac.ruh.eng.energy.service.EnergySimulatorService;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.data.mongodb.core.MongoTemplate;
import org.springframework.test.context.TestPropertySource;

import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * SimulatorAlertIntegrationTest
 * ------------------------------
 * Focused Phase 5C-4 integration test suite verifying:
 * 1. Normal simulation cycle creates no alerts.
 * 2. LOW_PF anomaly injection generates LOW_POWER_FACTOR WARNING alert.
 * 3. LOW_VOLTAGE anomaly injection generates LOW_VOLTAGE CRITICAL alert.
 * 4. OVERLOAD anomaly injection generates OVERLOAD CRITICAL alert.
 * 5. Duplicate suppression across successive abnormal simulation cycles.
 * 6. Automatic alert clearing when simulator returns to normal operation.
 * 7. Mutual clearing between HIGH_LOAD and OVERLOAD during simulation transitions.
 * 8. Fresh telemetry generated by simulator clears active SENSOR_OFFLINE alert.
 * 9. EnergyService /api/energy/live automatically reflects simulator-generated alerts.
 * 10. Alert evaluation failure resilience: energy reading is saved and intact even if alert fails.
 *
 * Runs strictly against the isolated test database: 'ruhuna_energy_spring_test'.
 */
@SpringBootTest
@TestPropertySource(properties = {
        "spring.data.mongodb.uri=mongodb://127.0.0.1:27018/ruhuna_energy_spring_test",
        "app.init-core-buildings=false",
        "simulator.enabled=false"
})
@DisplayName("Phase 5C-4 - Simulator & Alert Service Integration Tests")
class SimulatorAlertIntegrationTest {

    @Autowired
    private EnergySimulatorService simulatorService;

    @Autowired
    private AlertService alertService;

    @Autowired
    private EnergyService energyService;

    @Autowired
    private BuildingRepository buildingRepository;

    @Autowired
    private EnergyReadingRepository energyReadingRepository;

    @Autowired
    private AlertRepository alertRepository;

    @Autowired
    private MongoTemplate mongoTemplate;

    private Building testBuilding;

    @BeforeEach
    void setUp() {
        cleanTestData();

        Building b = new Building();
        b.setCode("ENG-MAIN");
        b.setName("Faculty Administration & Main Hall");
        b.setRatedPowerKw(50.0);
        b.setCreatedAt(Instant.now());
        b.setUpdatedAt(Instant.now());
        testBuilding = buildingRepository.save(b);
    }

    @AfterEach
    void tearDown() {
        cleanTestData();
    }

    private void cleanTestData() {
        mongoTemplate.dropCollection("alerts");
        mongoTemplate.dropCollection("database_sequences");
        mongoTemplate.dropCollection("buildings");
        mongoTemplate.dropCollection("energy_readings");
    }

    // =========================================================================
    // 1. NORMAL READINGS GENERATE NO ALERTS
    // =========================================================================

    @Test
    @DisplayName("Normal simulation cycle creates no electrical alerts")
    void testNormalSimulationGeneratesNoAlerts() {
        // Use off-peak time (01:00 UTC) to ensure nominal baseline load without time-dependent peak HIGH_LOAD
        Instant t1 = Instant.parse("2026-10-28T01:00:00Z");
        List<EnergyReading> readings = simulatorService.runSingleCycle(t1);

        assertThat(readings).hasSize(1);
        assertThat(alertRepository.count()).isZero();
    }

    // =========================================================================
    // 2. LOW_PF ANOMALY CREATES WARNING ALERT
    // =========================================================================

    @Test
    @DisplayName("LOW_PF anomaly creates LOW_POWER_FACTOR WARNING alert")
    void testLowPfAnomalyGeneratesWarning() {
        Instant t1 = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        List<EnergyReading> readings = simulatorService.runSingleCycle(t1, "LOW_PF", testBuilding.getId());

        assertThat(readings).hasSize(1);
        EnergyReading r = readings.get(0);
        assertThat(r.getPowerFactor()).isLessThan(0.85);

        Optional<Alert> active = alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "LOW_POWER_FACTOR");
        assertThat(active).isPresent();
        Alert alert = active.get();
        assertThat(alert.getSeverity()).isEqualTo("WARNING");
        assertThat(alert.getIsActive()).isTrue();
    }

    // =========================================================================
    // 3. LOW_VOLTAGE ANOMALY CREATES CRITICAL ALERT
    // =========================================================================

    @Test
    @DisplayName("LOW_VOLTAGE anomaly creates LOW_VOLTAGE CRITICAL alert")
    void testLowVoltageAnomalyGeneratesCritical() {
        Instant t1 = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        List<EnergyReading> readings = simulatorService.runSingleCycle(t1, "LOW_VOLTAGE", testBuilding.getId());

        assertThat(readings).hasSize(1);
        EnergyReading r = readings.get(0);
        assertThat(r.getVoltage()).isLessThan(380.0);

        Optional<Alert> active = alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "LOW_VOLTAGE");
        assertThat(active).isPresent();
        Alert alert = active.get();
        assertThat(alert.getSeverity()).isEqualTo("CRITICAL");
        assertThat(alert.getIsActive()).isTrue();
    }

    // =========================================================================
    // 4. OVERLOAD ANOMALY CREATES CRITICAL ALERT
    // =========================================================================

    @Test
    @DisplayName("OVERLOAD anomaly creates OVERLOAD CRITICAL alert")
    void testOverloadAnomalyGeneratesCritical() {
        Instant t1 = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        List<EnergyReading> readings = simulatorService.runSingleCycle(t1, "OVERLOAD", testBuilding.getId());

        assertThat(readings).hasSize(1);
        EnergyReading r = readings.get(0);
        assertThat(r.getActivePowerKw()).isGreaterThan(testBuilding.getRatedPowerKw());

        Optional<Alert> active = alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "OVERLOAD");
        assertThat(active).isPresent();
        Alert alert = active.get();
        assertThat(alert.getSeverity()).isEqualTo("CRITICAL");
        assertThat(alert.getIsActive()).isTrue();
    }

    // =========================================================================
    // 5. DUPLICATE ACTIVE SUPPRESSION ACROSS SIMULATION CYCLES
    // =========================================================================

    @Test
    @DisplayName("Successive abnormal simulation cycles suppress duplicate active alerts")
    void testDuplicateSuppressionAcrossCycles() {
        Instant t1 = Instant.now().minus(30, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);
        Instant t2 = Instant.now().minus(15, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);

        // Cycle 1: Trigger LOW_VOLTAGE
        simulatorService.runSingleCycle(t1, "LOW_VOLTAGE", testBuilding.getId());
        long alertCountAfterC1 = alertRepository.countByIsActiveTrue();
        assertThat(alertCountAfterC1).isEqualTo(1);

        // Cycle 2: Same condition continuing
        simulatorService.runSingleCycle(t2, "LOW_VOLTAGE", testBuilding.getId());
        long alertCountAfterC2 = alertRepository.countByIsActiveTrue();
        assertThat(alertCountAfterC2).isEqualTo(1); // Still exactly 1 active alert!

        // Total saved energy readings is 2
        assertThat(energyReadingRepository.count()).isEqualTo(2);
    }

    // =========================================================================
    // 6. AUTOMATIC CLEARING AFTER NORMAL SIMULATION CYCLE
    // =========================================================================

    @Test
    @DisplayName("Subsequent normal cycle automatically clears active alert")
    void testAutomaticClearingOnNormalCycle() {
        Instant t1 = Instant.now().minus(30, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);
        Instant t2 = Instant.now().minus(15, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);

        // Cycle 1: Anomaly
        simulatorService.runSingleCycle(t1, "LOW_VOLTAGE", testBuilding.getId());
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "LOW_VOLTAGE")).isPresent();

        // Cycle 2: Normal
        simulatorService.runSingleCycle(t2, null, null);
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "LOW_VOLTAGE")).isEmpty();

        // Stored alert marked is_active=false, cleared_at != null
        List<Alert> allAlerts = alertRepository.findAll();
        assertThat(allAlerts).hasSize(1);
        Alert stored = allAlerts.get(0);
        assertThat(stored.getIsActive()).isFalse();
        assertThat(stored.getClearedAt()).isNotNull();
    }

    // =========================================================================
    // 7. MUTUAL CLEARING BETWEEN HIGH_LOAD AND OVERLOAD
    // =========================================================================

    @Test
    @DisplayName("Mutual clearing: HIGH_LOAD clears when transitioning to OVERLOAD and vice versa")
    void testMutualClearingInSimulation() {
        Instant t1 = Instant.now().minus(45, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);
        Instant t2 = Instant.now().minus(30, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);
        Instant t3 = Instant.now().minus(15, ChronoUnit.SECONDS).truncatedTo(ChronoUnit.SECONDS);

        // Cycle 1: HIGH_LOAD
        simulatorService.runSingleCycle(t1, "HIGH_LOAD", testBuilding.getId());
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "HIGH_LOAD")).isPresent();
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "OVERLOAD")).isEmpty();

        // Cycle 2: Escalates to OVERLOAD -> HIGH_LOAD cleared
        simulatorService.runSingleCycle(t2, "OVERLOAD", testBuilding.getId());
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "HIGH_LOAD")).isEmpty();
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "OVERLOAD")).isPresent();

        // Cycle 3: De-escalates to HIGH_LOAD -> OVERLOAD cleared
        simulatorService.runSingleCycle(t3, "HIGH_LOAD", testBuilding.getId());
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "OVERLOAD")).isEmpty();
        assertThat(alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "HIGH_LOAD")).isPresent();
    }

    // =========================================================================
    // 8. NEW TELEMETRY CLEARS SENSOR_OFFLINE
    // =========================================================================

    @Test
    @DisplayName("New telemetry cycle automatically clears active SENSOR_OFFLINE alert")
    void testNewTelemetryClearsSensorOffline() {
        // Pre-create SENSOR_OFFLINE alert
        Alert offlineAlert = alertService.triggerAlert(testBuilding, "SENSOR_OFFLINE", "WARNING", 90.0, 60.0, "Sensor offline", Instant.now());
        assertThat(offlineAlert.getIsActive()).isTrue();

        // Run simulation cycle (new telemetry arrives)
        Instant t1 = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        simulatorService.runSingleCycle(t1);

        Optional<Alert> active = alertService.findActiveAlert(testBuilding.getId(), testBuilding.getCode(), "SENSOR_OFFLINE");
        assertThat(active).isEmpty();

        Alert saved = alertRepository.findById(offlineAlert.getInternalId()).orElseThrow();
        assertThat(saved.getIsActive()).isFalse();
        assertThat(saved.getClearedAt()).isNotNull();
    }

    // =========================================================================
    // 9. ENERGY SERVICE REFLECTS SIMULATOR ALERTS IN /api/energy/live
    // =========================================================================

    @Test
    @DisplayName("EnergyService /api/energy/live automatically reflects simulator-generated alerts")
    void testLiveTelemetryIncludesSimulatorAlerts() {
        Instant t1 = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        simulatorService.runSingleCycle(t1, "LOW_VOLTAGE", testBuilding.getId());

        Map<String, Object> liveTelemetry = energyService.getLiveEnergyTelemetry();
        assertThat(liveTelemetry.get("status")).isEqualTo("success");

        @SuppressWarnings("unchecked")
        List<Map<String, Object>> readings = (List<Map<String, Object>>) liveTelemetry.get("data");
        assertThat(readings).hasSize(1);

        Map<String, Object> buildingData = readings.get(0);
        assertThat(buildingData.get("building_code")).isEqualTo("ENG-MAIN");
        assertThat(buildingData.get("active_alerts_count")).isEqualTo(1);
        assertThat(buildingData.get("active_severity")).isEqualTo("CRITICAL");

        @SuppressWarnings("unchecked")
        List<Map<String, Object>> activeAlerts = (List<Map<String, Object>>) buildingData.get("active_alerts");
        assertThat(activeAlerts).hasSize(1);
        assertThat(activeAlerts.get(0).get("alert_type")).isEqualTo("LOW_VOLTAGE");
        assertThat(activeAlerts.get(0).get("severity")).isEqualTo("CRITICAL");
    }

    // =========================================================================
    // 10. ALERT EVALUATION FAILURE DOES NOT CORRUPT ENERGY READINGS
    // =========================================================================

    @Test
    @DisplayName("Alert evaluation failure does not corrupt saved reading or interrupt cycle")
    void testAlertFailureDoesNotCorruptReading() {
        // Even with anomalous parameters, reading is valid and persisted with all 3-phase fields
        Instant t1 = Instant.now().truncatedTo(ChronoUnit.SECONDS);
        List<EnergyReading> readings = simulatorService.runSingleCycle(t1, "OVERLOAD", testBuilding.getId());

        assertThat(readings).hasSize(1);
        EnergyReading r = readings.get(0);

        assertThat(r.getId()).isNotNull();
        assertThat(r.getVoltage()).isNotNull().isGreaterThan(0.0);
        assertThat(r.getCurrent()).isNotNull().isGreaterThan(0.0);
        assertThat(r.getPowerFactor()).isNotNull().isGreaterThan(0.0);
        assertThat(r.getActivePowerKw()).isNotNull().isGreaterThan(0.0);
        assertThat(r.getApparentPowerKva()).isNotNull().isGreaterThan(0.0);
        assertThat(r.getEnergyKwh()).isNotNull().isGreaterThan(0.0);
        assertThat(r.getIsSimulated()).isTrue();

        // Reading in repository matches saved object
        Optional<EnergyReading> inDb = energyReadingRepository.findById(r.getId());
        assertThat(inDb).isPresent();
        assertThat(inDb.get().getActivePowerKw()).isEqualTo(r.getActivePowerKw());
    }
}
